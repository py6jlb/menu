/**
 * Единый словарь повторяемости. Показатель — сколько РАЗНЫХ недель окна содержат
 * блюдо, а не число записей или приёмов пищи. Подписи и пояснения держим рядом,
 * чтобы список, карточка рецепта и подбор говорили одинаково.
 */

/** Компактная подпись повторяемости «🔁 N нед.». */
export function repetitionChip(count) {
  return `🔁 ${count} нед.`
}

/** Пояснение к бейджу повторяемости для всплывающей подсказки. */
export function repetitionTitle() {
  return 'В скольких разных неделях окна повторяемости блюдо стоит в плане. Повторения внутри одной недели считаются один раз.'
}

/** Пояснение окна повторяемости для экрана настроек: из скольких недель считаем. */
export function repetitionWindowNote(windowWeeks) {
  return `Повторяемость — число разных недель из ${windowWeeks} до выбранной включительно, где блюдо уже в плане. Повторы внутри одной недели считаются один раз.`
}
